import { guidedStoryFixture } from '@sherpa/fixtures';
import fs from 'node:fs/promises';
import { openBlocks, test, expect, sherpaAuth } from './sherpa-fixture.js';
const fixture = guidedStoryFixture();
test.setTimeout(90_000);

test('описание → блок → полный дифф → файл/строки в чате; порядок, переходы в обычном окне', async ({ page, launchSherpa }) => {
    const server = await launchSherpa('fixture-medium');
    const file = page.locator(`[data-reading-file="${fixture.first.fileId}"]`);
    await page.goto(server.url);
    await server.worker.register('codex', 'ru');
    const plan = await server.worker.next();
    expect((await server.worker.complete(plan.taskId ?? 0, JSON.stringify(fixture.outline))).stdout).not.toContain('rejected');
    await expect(page.locator('.story-guided h2')).toHaveText('Описание ПРа');
    await expect(page.locator('.story-code')).toHaveCount(0);
    await openBlocks(page);
    await expect(page.locator('.story-continuous-block > h2')).toHaveText(fixture.outline.stops.map((block) => block.title));
    await expect(page.locator('.story-main h1,.story-breadcrumb,.story-guide-pager')).toHaveCount(0);
    await expect(page.locator('.story-code')).toHaveCount(fixture.diff.files.length);
    await page.locator('.story-nav').getByRole('button', { name: fixture.first.path, exact: true }).click();
    await expect(file.locator('header code')).toHaveText(fixture.first.path);
    await expect(page.locator('.story-guided')).toContainText('Пояснение готовится');
    const changed = file.locator('.diff-row--add, .diff-row--del');
    await expect(changed).toHaveCount(fixture.first.additions + fixture.first.deletions);
    const patchRows = await file.locator('.diff-row').allTextContents();
    await file.locator('header').getByRole('button', { name: 'В чат', exact: true }).click();
    await page.getByRole('textbox', { name: 'Вопрос агенту' }).fill('Как файл участвует в решении?');
    await page.getByRole('button', { name: 'Закрыть чат', exact: true }).click();
    const section = await server.worker.next();
    expect((await server.worker.complete(section.taskId ?? 0, JSON.stringify(fixture.body))).stdout).not.toContain('rejected');
    await expect(page.locator('.story-inline-note')).toHaveCount(1);
    expect(await file.locator('.diff-row').allTextContents()).toEqual(patchRows);
    await page.locator('.story-inline-note').scrollIntoViewIfNeeded();
    await page.screenshot({ path: test.info().outputPath('sherpa-guided-explanation.png'), fullPage: false });
    await expect(file.locator('.story-file-description .md-blocks').first()).toContainText(fixture.body.stops[0]?.files[0]?.explanation.replaceAll('`', '') ?? '');
    await page.getByRole('button', { name: 'Чат', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Вопрос агенту' })).toHaveValue('Как файл участвует в решении?');
    await page.getByRole('textbox', { name: 'Вопрос агенту' }).press('Enter');
    const question = await server.worker.next();
    expect(question.type).toBe('chat');
    const fileContext = question.stdout.split('\n').find((line) => line.includes('attached-file-patch-'));
    expect(fileContext).toBeDefined();
    expect(await fs.readFile(fileContext?.trim() ?? '', 'utf8')).toContain(fixture.first.path);
    const location = `#code?path=${encodeURIComponent(fixture.anchor.path)}&side=${fixture.anchor.side}&start=${String(fixture.anchor.start)}&end=${String(fixture.anchor.start)}`;
    expect((await server.worker.complete(question.taskId ?? 0, `См. [важную строку](${location}).`)).stdout).not.toContain('rejected');
    await page.getByRole('button', { name: 'Свернуть всё', exact: true }).click();
    await page.getByRole('link', { name: 'важную строку' }).click();
    await expect(page.locator('.story-nav-block').first().locator('.story-block-toggle')).toHaveAttribute('aria-expanded', 'true');
    await expect(file.locator('.diff-row.is-selected')).not.toHaveCount(0);
    await page.getByRole('button', { name: 'Закрыть чат', exact: true }).click();
    await file.getByRole('button', { name: 'Раскрыть контекст файла', exact: true }).click();
    await expect(file.locator('[role=alert]')).toHaveCount(0);
    const selectable = file.locator('.diff-row[data-key]');
    const anchorRow = selectable.nth(20);
    const earlierRow = selectable.nth(18);
    const laterRow = selectable.nth(24);
    await anchorRow.click();
    await earlierRow.click({ modifiers: ['Shift'] });
    await expect(file.locator('.diff-row.is-selected')).toHaveCount(3);
    await laterRow.click({ modifiers: ['Shift'] });
    await expect(file.locator('.diff-row.is-selected')).toHaveCount(5);
    await anchorRow.click();
    await expect(file.locator('.diff-row.is-selected')).toHaveCount(1);
    await laterRow.click({ modifiers: ['Shift'] });
    await expect(file.locator('.diff-row.is-selected')).toHaveCount(5);
    await expect(page.getByRole('button', { name: 'Спросить об этих строках', exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: 'Чат', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Убрать диапазон из контекста', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Закрыть чат', exact: true }).click();
    await page.locator('.story-nav').getByRole('button', { name: 'Все изменения', exact: true }).click();
    await expect(page.locator('.story-return')).toHaveText(`К рассказу · ${fixture.first.path}`);
    await page.locator('.story-return').click();
    await expect(file.locator('header code')).toHaveText(fixture.first.path);
    await expect(file.locator('.diff-row.is-selected')).toHaveCount(5);
    await file.locator('.diff-row').nth(20).focus();
    await page.evaluate(() => { window.scrollBy(0, 250); });
    const point = await file.evaluate((root) => {
        const top = Math.max(document.querySelector('.story-preparation')?.getBoundingClientRect().bottom ?? 0, document.querySelector('.story-topbar')?.getBoundingClientRect().bottom ?? 0) + 12;
        const row = [...root.querySelectorAll<HTMLElement>('.diff-row[data-key]')].find((entry) => entry.getBoundingClientRect().bottom > top);
        return { key: row?.dataset.key ?? '', y: row?.getBoundingClientRect().top ?? 0 };
    });
    for (let i = 0; i < 3; i += 1) {
        await page.locator('.story-nav').getByRole('button', { name: 'Описание ПРа', exact: true }).click();
        await openBlocks(page);
        const row = file.locator(`.diff-row[data-key="${point.key}"]`);
        await expect(async () => { expect(Math.abs(((await row.boundingBox())?.y ?? 9999) - point.y)).toBeLessThan(3); }).toPass();
    }
    await page.screenshot({ path: test.info().outputPath('sherpa-guided-file.png'), fullPage: false });
    await page.locator('.story-nav-block .story-block-visit').nth(1).click();
    const related = page.locator('.story-related button').first();
    await related.click();
    await expect(file.locator('header code')).toHaveText(fixture.first.path);
    await page.locator('.story-guided > .story-return').click();
    await expect(related).toBeInViewport();
    await expect(related).toBeFocused();
});

test('провал и локальный повтор сохраняют план, дифф и открытый файл', async ({ page, launchSherpa }) => {
    const server = await launchSherpa('fixture-medium');
    const file = page.locator(`[data-reading-file="${fixture.first.fileId}"]`);
    await page.goto(server.url); await server.worker.register('codex', 'ru');
    const plan = await server.worker.next();
    await server.worker.complete(plan.taskId ?? 0, JSON.stringify(fixture.outline));
    await openBlocks(page);
    await page.locator('.story-nav').getByRole('button', { name: fixture.first.path, exact: true }).click();
    const section = await server.worker.next();
    await server.worker.fail(section.taskId ?? 0, 'Synthetic explanation failure');
    await expect(page.getByRole('button', { name: 'Повторить пояснение', exact: true }).first()).toBeVisible();
    const before = await file.locator('.diff-row').allTextContents();
    await page.getByRole('button', { name: 'Повторить пояснение', exact: true }).first().click();
    const retry = await server.worker.next();
    expect(retry.type).toBe('route.section');
    expect((await server.worker.complete(retry.taskId ?? 0, JSON.stringify({ contractVersion: 3, stops: [fixture.body.stops[0]] }))).stdout).not.toContain('rejected');
    await expect(page.locator('.story-inline-note')).toHaveCount(1);
    await expect(file.locator('header code')).toHaveText(fixture.first.path);
    expect(await file.locator('.diff-row').allTextContents()).toEqual(before);
});

test('выделение синхронизировано с чатом, удаление не воскресает, агент получает строки', async ({ page, launchSherpa }) => {
    page.setDefaultTimeout(10_000);
    const server = await launchSherpa('fixture-medium');
    const file = page.locator(`[data-reading-file="${fixture.first.fileId}"]`);
    await page.goto(server.url); await server.worker.register('codex', 'ru');
    const plan = await server.worker.next();
    await server.worker.complete(plan.taskId ?? 0, JSON.stringify(fixture.outline));
    const section = await server.worker.next();
    await server.worker.complete(section.taskId ?? 0, JSON.stringify(fixture.body));
    await openBlocks(page);
    await page.locator('.story-nav').getByRole('button', { name: fixture.first.path, exact: true }).click();
    const start = fixture.anchor.start;
    const prefix = fixture.anchor.side === 'old' ? 'd' : 'a';
    const row = file.locator(`.diff-row[data-key="${prefix}${String(start)}"]`);
    await row.click();
    await expect(page.locator('.story-chat')).toHaveCount(0);
    await expect(row).toBeFocused();
    await expect(page.getByRole('toolbar', { name: 'Выбраны строки' })).toHaveCount(0);
    await page.getByRole('button', { name: 'Чат', exact: true }).click();
    const input = page.getByRole('textbox', { name: 'Вопрос агенту' });
    const quote = page.locator('.chat-panel__selection-quote');
    await expect(quote).not.toBeEmpty();
    await expect(page.locator('.chat-panel__contexts')).toContainText(fixture.first.path);
    await input.fill('Что меняется в этих строках?');
    const nextRow = row.locator('xpath=following-sibling::div[contains(@class,"diff-row")][1]');
    await nextRow.locator('.diff-row__gutter--code').click({ modifiers: ['Shift'] });
    await expect(file.locator('.diff-row.is-selected')).toHaveCount(2);
    await expect(input).toHaveValue('Что меняется в этих строках?');
    const code = await quote.textContent();
    expect(code).not.toBeNull();
    await page.getByRole('button', { name: 'Закрыть чат', exact: true }).click();
    await page.reload();
    await expect(file.locator('.diff-row.is-selected')).toHaveCount(2);
    await page.getByRole('button', { name: 'Чат', exact: true }).click();
    await expect(quote).toHaveText(code ?? '');
    await expect(input).toHaveValue('Что меняется в этих строках?');
    await input.press('Enter');
    const question = await server.worker.next();
    expect(question.type).toBe('chat');
    const questionFile = question.stdout.split('\n').find((line) => line.endsWith('question.md'))?.trim();
    const payload = await fs.readFile(questionFile ?? '', 'utf8');
    expect(payload).toContain(`Selected range: ${fixture.first.path}:${String(start)}-`);
    expect(payload).toContain(JSON.stringify(code));
    expect(payload).not.toContain('Whole pull request.');
    const target = `#code?path=${encodeURIComponent(fixture.first.path)}&side=${fixture.anchor.side}&start=${String(start + 1)}&end=${String(start + 1)}`;
    await server.worker.complete(question.taskId ?? 0, `Выбранные строки задают условие изменения заказа. См. [строку](${target}).`);
    await page.getByRole('link', { name: 'строку', exact: true }).click();
    await expect(file.locator('.diff-row.is-selected')).toHaveCount(1);
    await expect(quote).toHaveText(code ?? '');
    await page.screenshot({ path: test.info().outputPath('selected-code-chat.png') });
    await input.fill('Следующий вопрос');
    await page.getByRole('button', { name: 'Убрать диапазон из контекста', exact: true }).click();
    await expect(file.locator('.diff-row.is-selected')).toHaveCount(0);
    await expect(quote).toHaveCount(0);
    await expect(input).toHaveValue('Следующий вопрос');
    await expect(input).toBeFocused();
    await page.locator('.story-nav').getByRole('button', { name: 'Все изменения', exact: true }).click();
    await expect(file.locator('.diff-row.is-selected')).toHaveCount(0);
    await file.locator('.diff-row[data-key]').first().locator('.diff-row__gutter--code').click();
    await expect(page.getByRole('dialog', { name: 'Чат с агентом', exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Чат', exact: true })).toHaveCount(0);
    await expect(quote).not.toBeEmpty();
    await page.getByRole('button', { name: 'Убрать диапазон из контекста', exact: true }).click();
    await page.reload();
    await expect(file.locator('.diff-row.is-selected')).toHaveCount(0);
    await expect(quote).toHaveCount(0);
    const response = await page.request.get(new URL('/api/ui/review/chat', server.url).href, { headers: sherpaAuth(server) });
    const saved = await response.json() as { exchanges: { anchor: { path: string; side: string; start: number; end: number; selectedText: string } }[] };
    expect(saved.exchanges[0]?.anchor).toMatchObject({ path: fixture.first.path, side: fixture.anchor.side, start, end: start + 1, selectedText: code });
});
