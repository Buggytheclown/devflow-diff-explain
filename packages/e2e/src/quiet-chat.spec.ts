import fs from 'node:fs/promises';
import { architectureStoryFixture } from '@sherpa/fixtures';
import { test, expect, sherpaAuth } from './sherpa-fixture.js';

const fixture = architectureStoryFixture();
test('весь PR по умолчанию; явный файл → строки → удаление, reload и спокойное чтение ответа', async ({ page, launchSherpa }) => {
    const server = await launchSherpa('fixture-medium');
    await page.goto(server.url);
    await server.worker.register('codex', 'ru');
    await page.locator('.story-nav').getByRole('button', { name: 'Все изменения', exact: true }).click();
    await expect(page.locator('.story-code .diff-row')).not.toHaveCount(0);
    const originalPath = await page.locator('.story-code header code').textContent() ?? '';
    await page.getByRole('button', { name: 'Чат', exact: true }).click();
    await expect(page.locator('.story-chat-context,.chat-panel__empty')).toHaveCount(0);
    await expect(page.locator('.chat-panel__header')).toContainText('Чат');
    await expect(page.locator('.chat-panel__contexts')).toHaveCount(0);
    await page.screenshot({ path: test.info().outputPath('quiet-chat-empty.png') });
    await page.getByRole('textbox', { name: 'Вопрос агенту' }).fill('Как устроен весь PR?');
    await page.getByRole('textbox', { name: 'Вопрос агенту' }).press('Enter');
    const first = await server.worker.next(); expect(first.type).toBe('chat');
    await server.worker.complete(first.taskId ?? 0, 'Этот PR меняет правило и его применение в обработчике.');

    await page.getByRole('button', { name: 'Закрыть чат', exact: true }).click();
    await page.locator('.story-code header').getByRole('button', { name: 'В чат', exact: true }).click();
    await expect(page.locator('.chat-panel__context-label')).toHaveText(originalPath);
    await page.getByRole('textbox', { name: 'Вопрос агенту' }).fill('Зачем изменили этот файл?');
    await page.locator('.story-nav-file').nth(1).click();
    await expect(page.locator('.chat-panel__context-label')).toHaveText(originalPath);
    await page.reload();
    await expect(page.getByRole('textbox', { name: 'Вопрос агенту' })).toHaveValue('Зачем изменили этот файл?');
    await expect(page.locator('.chat-panel__context-label')).toHaveText(originalPath);
    await page.screenshot({ path: test.info().outputPath('quiet-chat-file-attachment.png') });
    await page.getByRole('textbox', { name: 'Вопрос агенту' }).press('Enter');
    const attached = await server.worker.next(); expect(attached.type).toBe('chat');
    const patch = attached.stdout.split('\n').find((line) => line.includes('attached-file-patch-'));
    expect(patch).toBeDefined(); expect(await fs.readFile(patch?.trim() ?? '', 'utf8')).toContain(originalPath);
    await server.worker.complete(attached.taskId ?? 0, 'Файл участвует в проверке и применении правила.');

    await page.locator('.story-code .diff-row[data-key]').first().locator('.diff-row__gutter--code').click();
    await expect(page.getByRole('button', { name: 'Убрать файл из контекста', exact: true })).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Убрать диапазон из контекста', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Убрать диапазон из контекста', exact: true }).click();
    await expect(page.locator('.chat-panel__contexts')).toHaveCount(0);
    await expect(page.locator('.story-code .diff-row.is-selected')).toHaveCount(0);
    await page.getByRole('textbox', { name: 'Вопрос агенту' }).fill('Снова вопрос по всему PR');
    await page.getByRole('textbox', { name: 'Вопрос агенту' }).press('Enter');
    const general = await server.worker.next(); expect(general.type).toBe('chat');
    expect(general.stdout).not.toContain('attached-file-patch-');
    const longAnswer = 'Ответ остаётся доступным для чтения.\n\n' + 'Правило проверяется до сохранения изменения, чтобы отказ не оставлял частично записанных данных.\n\n'.repeat(15);
    await server.worker.complete(general.taskId ?? 0, longAnswer);
    await expect(page.locator('.chat-message--agent').last()).toContainText('Ответ остаётся доступным');
    await page.locator('.chat-panel__feed').evaluate((element) => { element.scrollTop = 0; });

    const overview = await server.worker.next(); expect(overview.type).toBe('route.skeleton');
    await server.worker.complete(overview.taskId ?? 0, JSON.stringify(fixture.outline));
    const files = await server.worker.next(); await server.worker.complete(files.taskId ?? 0, JSON.stringify(fixture.body));
    await expect(page.locator('.story-preparation--ready summary')).toHaveText('✓ Разбор готов');
    await expect(page.locator('.story-preparation--ready [role=progressbar]')).toBeHidden();
    await expect(page.locator('.chat-message--agent').last()).toContainText('Ответ остаётся доступным');
    expect(await page.locator('.chat-panel__feed').evaluate((element) => element.scrollTop)).toBe(0);
    await page.locator('.story-preparation--ready summary').click();
    await expect(page.locator('.story-preparation--ready [role=progressbar]')).toBeVisible();
    await page.locator('.story-preparation--ready summary').click();
    const response = await page.request.get(new URL('/api/ui/review/chat', server.url).href, { headers: sherpaAuth(server) });
    const data = await response.json() as { exchanges: { anchor: unknown; explanation: { file?: { path: string }; sectionId?: string } }[] };
    expect(data.exchanges[0]?.explanation.file).toBeUndefined();
    expect(data.exchanges[0]?.explanation.sectionId).toBeUndefined();
    expect(data.exchanges[1]?.explanation.file?.path).toBe(originalPath);
    expect(data.exchanges[2]?.explanation.file).toBeUndefined();
    expect(data.exchanges[2]?.anchor).toBeNull();
    await page.screenshot({ path: test.info().outputPath('quiet-chat-reading.png') });
});
