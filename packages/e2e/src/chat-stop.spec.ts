import { architectureStoryFixture } from '@sherpa/fixtures';
import { test, expect } from './sherpa-fixture.js';

test('композер: очередь → стоп с прогрессом → отмена с черновиком → новый ответ', async ({ page, launchSherpa }) => {
    const server = await launchSherpa('fixture-medium');
    const fixture = architectureStoryFixture();
    await page.goto(server.url);
    await server.worker.register('codex', 'ru');
    const overview = await server.worker.next();
    await server.worker.complete(overview.taskId ?? 0, JSON.stringify(fixture.outline));
    const files = await server.worker.next();
    await server.worker.complete(files.taskId ?? 0, JSON.stringify(fixture.body));
    await page.getByRole('button', { name: 'Чат', exact: true }).click();
    const input = page.getByRole('textbox', { name: 'Вопрос агенту' });
    const send = page.getByRole('button', { name: 'Отправить', exact: true });
    const stop = page.getByRole('button', { name: 'Остановить', exact: true });
    const ring = page.locator('.chat-panel__stop-ring');
    const height = await input.evaluate((element) => element.getBoundingClientRect().height);
    await input.fill('Вопрос в очереди');
    await send.click();
    await expect(stop).toBeEnabled();
    await stop.click();
    await expect(send).toBeVisible();
    await expect(ring).toHaveCount(0);
    await expect(page.locator('.chat-message--failed')).toContainText('Вопрос отменён');

    await input.fill('Почему проверка до сохранения?');
    await send.click();
    const question = await server.worker.next();
    expect(question.type).toBe('chat');
    await server.worker.progress(question.taskId ?? 0, 'Проверяю порядок сохранения');
    await expect(page.locator('.chat-message__activity')).toHaveText('Проверяю порядок сохранения');
    await expect(stop).toBeEnabled();
    await expect(page.locator('.chat-message--agent .chat-message__action').last()).toHaveText('Повторить');
    await expect(ring).toHaveCSS('animation-name', 'chat-stop-spin');
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await expect(ring).toHaveCSS('animation-name', 'none');
    await page.emulateMedia({ reducedMotion: 'no-preference' });
    await input.fill('Следующий вопрос\n' + 'Строка черновика\n'.repeat(4));
    expect(await input.evaluate((element) => element.getBoundingClientRect().height)).toBeGreaterThan(height);
    await input.press('Enter');
    await expect(page.locator('.chat-message--you')).toHaveCount(2);
    await page.screenshot({ path: test.info().outputPath('chat-stop-running.png') });
    await stop.click();
    await expect(send).toBeEnabled();
    await expect(ring).toHaveCount(0);
    await expect(input).toHaveValue('Следующий вопрос\n' + 'Строка черновика\n'.repeat(4));
    await expect(page.locator('.chat-panel__cancelled-lease')).toBeVisible();
    // Агент узнаёт об отмене при следующем обращении; результат уже не становится ответом.
    await server.worker.complete(question.taskId ?? 0, 'Поздний ответ отменённой задачи');
    await expect(page.locator('.chat-message--agent')).not.toContainText(['Поздний ответ отменённой задачи']);
    await input.fill('Новый вопрос');
    await send.click();
    const next = await server.worker.next();
    expect(next.type).toBe('chat');
    await server.worker.complete(next.taskId ?? 0, 'Проверка выполняется перед записью.');
    await expect(send).toBeVisible();
    await expect(ring).toHaveCount(0);
    await expect(page.locator('.chat-message--agent').last()).toContainText('перед записью');
});
