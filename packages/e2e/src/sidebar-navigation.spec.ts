import { architectureStoryFixture } from '@sherpa/fixtures';
import { test, expect } from './sherpa-fixture.js';

const fixture = architectureStoryFixture();
test('один маршрут слева: сворачивание, прокрутка, готовность в шапке и новое открытие', async ({ page, launchSherpa }) => {
    const server = await launchSherpa('fixture-medium');
    await page.goto(server.url); await server.worker.register('codex', 'ru');
    const nav = page.locator('.story-nav');
    await expect(nav).toBeVisible();
    await expect(nav.locator('.story-skeleton')).toBeVisible();
    await expect(page.locator('.story-topbar nav,.story-overview-route')).toHaveCount(0);
    await nav.getByRole('button', { name: 'Все изменения', exact: true }).click();
    await expect(page.locator('.story-code')).toBeVisible();
    await nav.getByRole('button', { name: 'Описание ПРа', exact: true }).click();
    const outline = await server.worker.next(); await server.worker.complete(outline.taskId ?? 0, JSON.stringify(fixture.outline));
    const blocks = fixture.snapshot.tourOrder.map((id) => fixture.snapshot.stops.find((block) => block.id === id));
    const first = blocks[0], second = blocks[1]; if (first === undefined || second === undefined) throw Error('Need two blocks');
    const a = nav.getByRole('region', { name: first.title, exact: true });
    const b = nav.getByRole('region', { name: second.title, exact: true });
    const visitA = a.locator('.story-block-visit'), visitB = b.locator('.story-block-visit');
    const toggleA = a.locator('.story-block-toggle'), toggleB = b.locator('.story-block-toggle');
    await expect(nav.locator('.story-block-toggle[aria-expanded=true]')).toHaveCount(0);
    await page.screenshot({ path: test.info().outputPath('overview-sidebar-collapsed.png') });
    const expand = nav.getByRole('button', { name: 'Развернуть всё', exact: true });
    await expand.focus(); await expand.press('Enter');
    await expect(nav.locator('.story-block-toggle[aria-expanded=true]')).toHaveCount(blocks.length);
    await expect(nav.locator('details:not([open])')).toHaveCount(0);
    const collapse = nav.getByRole('button', { name: 'Свернуть всё', exact: true });
    await collapse.focus(); await collapse.press('Space');
    await expect(nav.locator('.story-block-toggle[aria-expanded=true]')).toHaveCount(0);
    await toggleA.click();
    await expect(a.locator('details[open]')).toHaveCount(0);
    await toggleA.click();
    await visitA.click(); await expect(toggleA).toHaveAttribute('aria-expanded', 'true');
    await expect(toggleB).toHaveAttribute('aria-expanded', 'false');
    const firstFile = first.guidedFiles?.[0], nextFile = first.guidedFiles?.[1];
    if (firstFile === undefined || nextFile === undefined) throw Error('Need two files in first block');
    await a.getByRole('button', { name: firstFile.path, exact: true }).click();
    const firstCard = page.locator(`[data-reading-file="${firstFile.fileId}"]`);
    const position = await firstCard.evaluate((element) => element.getBoundingClientRect().top);
    await toggleA.click(); await expect(toggleA).toHaveAttribute('aria-expanded', 'false');
    expect(await firstCard.evaluate((element) => element.getBoundingClientRect().top)).toBe(position);
    const body = await server.worker.next(); await server.worker.complete(body.taskId ?? 0, JSON.stringify(fixture.body));
    await expect(page.locator('.story-topbar .story-preparation--ready')).toBeVisible();
    await expect(page.locator('.story-app > .story-preparation')).toHaveCount(0);
    await expect(toggleA).toHaveAttribute('aria-expanded', 'false');
    await page.locator('.story-preparation-complete summary').click();
    await expect(page.locator('.story-preparation-popover')).toContainText('100%');
    await page.locator('.story-preparation-complete summary').click();
    await scrollToFile(nextFile.fileId);
    await expect(a).toHaveAttribute('data-current-block', 'true');
    await expect(visitA).toHaveAttribute('aria-current', 'location');
    await expect(toggleA).toHaveAttribute('aria-expanded', 'false');
    await expect(a.locator('.story-nav-file[aria-current=page]')).toBeHidden();
    await visitB.click(); await expect(toggleB).toHaveAttribute('aria-expanded', 'true');
    await expect(toggleA).toHaveAttribute('aria-expanded', 'false');
    await visitA.click(); await expect(toggleA).toHaveAttribute('aria-expanded', 'true');
    await expect(toggleB).toHaveAttribute('aria-expanded', 'true');
    const targetB = second.guidedFiles?.[0]; if (targetB === undefined) throw Error('Need file');
    await scrollToFile(targetB.fileId);
    await expect(b.locator('.story-nav-file[aria-current=page]')).toBeInViewport();
    await nav.getByRole('button', { name: 'Свернуть всё', exact: true }).click();
    await expect(toggleB).toHaveAttribute('aria-expanded', 'false');
    await visitB.click(); await expect(toggleB).toHaveAttribute('aria-expanded', 'true');
    await b.getByRole('button', { name: targetB.path, exact: true }).click();
    const folder = b.locator('.story-nav-file[aria-current=page]').locator('xpath=ancestor::details[1]');
    await folder.locator(':scope > summary').click();
    await expect(b.locator('.story-nav-file[aria-current=page]')).toBeHidden();
    await page.mouse.move(800, 300); await page.mouse.wheel(0, 10);
    await expect(folder).not.toHaveAttribute('open', '');
    await page.reload();
    await expect(nav.locator('.story-block-toggle[aria-expanded=true]')).toHaveCount(1);
    await expect(toggleB).toHaveAttribute('aria-expanded', 'true');
    await expect(b.locator('.story-nav-file[aria-current=page]')).toBeInViewport();
    await nav.getByRole('button', { name: 'Описание ПРа', exact: true }).click();
    await expect(toggleB).toHaveAttribute('aria-expanded', 'true');
    await page.reload();
    await expect(nav.locator('.story-block-toggle[aria-expanded=true]')).toHaveCount(0);
    await expect(nav.getByRole('button', { name: 'Описание ПРа', exact: true })).toHaveAttribute('aria-current', 'page');
    await page.screenshot({ path: test.info().outputPath('overview-header-ready.png') });

    async function scrollToFile(id: string) {
        const delta = await page.locator(`[data-reading-file="${id}"]`).evaluate((element) => element.getBoundingClientRect().top - Math.max(document.querySelector('.story-topbar')?.getBoundingClientRect().bottom ?? 0, document.querySelector('.story-preparation')?.getBoundingClientRect().bottom ?? 0) - 12);
        await page.mouse.move(800, 300); await page.mouse.wheel(0, delta);
        await expect(nav.locator('.story-nav-file[aria-current=page]')).toHaveAttribute('aria-label', fixture.diff.files.find((file) => file.fileId === id)?.path ?? 'missing');
    }
});
